//! The network listener's self-signed TLS identity.
//!
//! The network listener is TLS only. Its certificate is generated on first
//! use under `<data>/daemon/tls/` and covers a fixed set of loopback names
//! plus whatever the operator lists in `daemon.network.listeners.*.tlsSans`:
//!
//! * always `localhost`, `127.0.0.1` and `::1`;
//! * the listen IP, unless it is unspecified (`0.0.0.0` / `[::]`);
//! * every `daemon.network.listeners.*.tlsSans` entry (DNS name or IP literal).
//!
//! `tls/sans.json` records the set a certificate was made for. When the
//! wanted set differs, [`AuthEngine::ensure_network_tls`] makes a new key and
//! certificate and reports `regenerated = true`; the caller reloads the new
//! material into the running listener with
//! [`TlsMaterial::rustls_server_config`] (for example through
//! `axum_server::tls_rustls::RustlsConfig::reload_from_config`) without
//! dropping the socket.
//!
//! Files are written owner-only and replaced atomically. `sans.json` is
//! removed before and written after the key and certificate, so an
//! interrupted regeneration is always detected (no record → regenerate) and
//! a mismatched key/certificate pair is never adopted.

use std::collections::BTreeSet;
use std::io::Write as _;
use std::net::IpAddr;
use std::path::Path;
use std::sync::Arc;

use chrono::Datelike;
use ring::digest;
use serde::{Deserialize, Serialize};

use crate::data::config::network::TlsSan;
use crate::data::fs::daemon_paths::DaemonPaths;
use crate::data::fs::private_files::{
    create_private_dir, create_private_file_new, read_private_json, remove_private_file,
    sync_private_dir, write_private_json_atomic,
};
use crate::engine::auth::{hex_encode, AuthEngine, TlsMaterial};
use crate::engine::error::EngineError;

/// The names every network certificate covers, whatever the configuration.
pub const ALWAYS_SANS: &[&str] = &["localhost", "127.0.0.1", "::1"];

/// A certificate and key plus the subject alternative names it was made for
/// (canonical spellings, sorted).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TlsIdentity {
    pub material: TlsMaterial,
    pub sans: Vec<String>,
}

/// `tls/sans.json`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
struct SansRecord {
    sans: Vec<String>,
    /// Rotate the short-lived server certificate before it expires. Missing
    /// on identities generated by earlier versions, which must be replaced.
    #[serde(default)]
    renew_after_unix: Option<i64>,
}

/// The SAN set for a listen IP and the configured extras, canonical and
/// sorted: IPs in `IpAddr` display form, DNS names lowercase.
pub fn network_sans(listen_ips: &[IpAddr], extra: &[TlsSan]) -> Vec<String> {
    let mut set: BTreeSet<String> = ALWAYS_SANS.iter().map(|s| s.to_string()).collect();
    for listen_ip in listen_ips {
        if !listen_ip.is_unspecified() {
            set.insert(listen_ip.to_string());
        }
    }
    for san in extra {
        set.insert(match san {
            TlsSan::Dns(name) => name.to_ascii_lowercase(),
            TlsSan::Ip(ip) => ip.to_string(),
        });
    }
    set.into_iter().collect()
}

impl AuthEngine {
    /// Load or (re)generate the network certificate under `paths.tls_dir()`.
    ///
    /// The SAN set is [`network_sans`]`(listen_ip, extra)`. When a certificate
    /// for exactly that set is on disk it is loaded and `regenerated` is
    /// `false`; otherwise a fresh key and certificate replace it and
    /// `regenerated` is `true`, telling the caller to reload the running
    /// listener and warn that pinned clients must re-pin.
    pub fn ensure_network_tls(
        &self,
        paths: &DaemonPaths,
        listen_ips: &[IpAddr],
        extra: &[TlsSan],
    ) -> Result<(TlsIdentity, bool), EngineError> {
        let wanted = network_sans(listen_ips, extra);
        if let Some(identity) = self.load_network_tls(paths)? {
            if identity.sans == wanted {
                return Ok((identity, false));
            }
        }
        Ok((generate_network_tls(paths, wanted)?, true))
    }

    /// The certificate on disk, or `None` when there is no complete one
    /// (missing key, certificate or SAN record). An unsafe file (symlink,
    /// readable by others, foreign owner) is an error.
    pub fn load_network_tls(
        &self,
        paths: &DaemonPaths,
    ) -> Result<Option<TlsIdentity>, EngineError> {
        let Some(record) = read_private_json::<SansRecord>(&paths.tls_sans_file())? else {
            return Ok(None);
        };
        if record
            .renew_after_unix
            .is_none_or(|deadline| deadline <= chrono::Utc::now().timestamp())
        {
            return Ok(None);
        }
        let (Some(cert_pem), Some(key_pem)) = (
            read_private_text(&paths.tls_cert_file())?,
            read_private_text(&paths.tls_key_file())?,
        ) else {
            return Ok(None);
        };
        let fingerprint_sha256_hex = der_fingerprint(&cert_pem)?;
        let mut sans = record.sans;
        sans.sort();
        sans.dedup();
        Ok(Some(TlsIdentity {
            material: TlsMaterial {
                cert_pem,
                key_pem,
                fingerprint_sha256_hex,
            },
            sans,
        }))
    }
}

impl TlsMaterial {
    /// A rustls server configuration for this certificate and key, with the
    /// ring provider selected per server (never the process default) and
    /// ALPN `h2`, `http/1.1`. Hand it to a running listener to swap
    /// certificates live.
    pub fn rustls_server_config(&self) -> Result<Arc<rustls::ServerConfig>, EngineError> {
        use rustls::pki_types::{pem::PemObject, CertificateDer, PrivateKeyDer};
        let invalid = || EngineError::Auth("TLS setup: invalid certificate or private key".into());
        let certificates = CertificateDer::pem_slice_iter(self.cert_pem.as_bytes())
            .collect::<Result<Vec<_>, _>>()
            .map_err(|_| invalid())?;
        let key = PrivateKeyDer::from_pem_slice(self.key_pem.as_bytes()).map_err(|_| invalid())?;
        let mut config = rustls::ServerConfig::builder_with_provider(Arc::new(
            rustls::crypto::ring::default_provider(),
        ))
        .with_safe_default_protocol_versions()
        .map_err(|_| invalid())?
        .with_no_client_auth()
        .with_single_cert(certificates, key)
        .map_err(|_| invalid())?;
        config.alpn_protocols = vec![b"h2".to_vec(), b"http/1.1".to_vec()];
        Ok(Arc::new(config))
    }
}

fn generate_network_tls(
    paths: &DaemonPaths,
    sans: Vec<String>,
) -> Result<TlsIdentity, EngineError> {
    let dir = paths.tls_dir();
    create_private_dir(&dir)?;
    // Invalidate first: from here until the record is rewritten, any reader
    // sees "no certificate" and regenerates rather than pairing halves.
    remove_private_file(&paths.tls_sans_file())?;

    let mut params = rcgen::CertificateParams::default();
    params.subject_alt_names = sans
        .iter()
        .map(|san| match san.parse::<IpAddr>() {
            Ok(ip) => Ok(rcgen::SanType::IpAddress(ip)),
            Err(_) => rcgen::string::Ia5String::try_from(san.as_str())
                .map(rcgen::SanType::DnsName)
                .map_err(|e| EngineError::Auth(format!("TLS SAN {san:?}: {e}"))),
        })
        .collect::<Result<_, _>>()?;
    let set_hash = {
        let h = digest::digest(&digest::SHA256, sans.join(",").as_bytes());
        hex_encode(&h.as_ref()[..4])
    };
    params.distinguished_name = rcgen::DistinguishedName::new();
    params.distinguished_name.push(
        rcgen::DnType::CommonName,
        format!("awman-daemon-{set_hash}"),
    );
    // Apple requires serverAuth EKU and a lifetime of at most 825 days for
    // locally trusted TLS server certificates. Keep ours within one year.
    let today = chrono::Utc::now().date_naive();
    let expires = today
        .checked_add_signed(chrono::Duration::days(365))
        .ok_or_else(|| EngineError::Auth("TLS certificate date overflow".into()))?;
    params.not_before = rcgen::date_time_ymd(today.year(), today.month() as u8, today.day() as u8);
    params.not_after =
        rcgen::date_time_ymd(expires.year(), expires.month() as u8, expires.day() as u8);
    params.is_ca = rcgen::IsCa::ExplicitNoCa;
    params.key_usages = vec![rcgen::KeyUsagePurpose::DigitalSignature];
    params.extended_key_usages = vec![rcgen::ExtendedKeyUsagePurpose::ServerAuth];

    let key_pair =
        rcgen::KeyPair::generate().map_err(|e| EngineError::Auth(format!("TLS keygen: {e}")))?;
    let cert = params
        .self_signed(&key_pair)
        .map_err(|e| EngineError::Auth(format!("TLS self-sign: {e}")))?;
    let cert_pem = cert.pem();
    let key_pem = key_pair.serialize_pem();
    let fingerprint_sha256_hex = hex_encode(digest::digest(&digest::SHA256, cert.der()).as_ref());

    write_private_atomic(&paths.tls_key_file(), key_pem.as_bytes())?;
    write_private_atomic(&paths.tls_cert_file(), cert_pem.as_bytes())?;
    // Informational only; never used for an auth decision.
    write_private_atomic(
        &paths.tls_fingerprint_file(),
        fingerprint_sha256_hex.as_bytes(),
    )?;
    write_private_json_atomic(
        &paths.tls_sans_file(),
        &SansRecord {
            sans: sans.clone(),
            renew_after_unix: Some(chrono::Utc::now().timestamp() + 300 * 86_400),
        },
        || Ok(()),
    )?;

    Ok(TlsIdentity {
        material: TlsMaterial {
            cert_pem,
            key_pem,
            fingerprint_sha256_hex,
        },
        sans,
    })
}

/// SHA-256 over the first certificate's DER bytes, lowercase hex.
fn der_fingerprint(cert_pem: &str) -> Result<String, EngineError> {
    use rustls::pki_types::{pem::PemObject, CertificateDer};
    let der = CertificateDer::from_pem_slice(cert_pem.as_bytes())
        .map_err(|e| EngineError::Auth(format!("TLS certificate is not valid PEM: {e}")))?;
    Ok(hex_encode(
        digest::digest(&digest::SHA256, der.as_ref()).as_ref(),
    ))
}

/// Read a private text file through the same safety checks as the JSON
/// records (no symlinks, owner-only, single link). `None` when absent.
fn read_private_text(path: &Path) -> Result<Option<String>, EngineError> {
    // The private-file helpers only parse JSON; wrapping the bytes in a JSON
    // string would change the on-disk format, so check metadata here instead.
    let meta = match std::fs::symlink_metadata(path) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(EngineError::io(path, e)),
    };
    let refuse = |why: &str| {
        EngineError::Auth(format!(
            "refusing TLS file {}: {why}; remove the tls directory and retry",
            path.display()
        ))
    };
    if !meta.file_type().is_file() {
        return Err(refuse("not a regular file (symlinks are refused)"));
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        if meta.nlink() != 1 {
            return Err(refuse("it has other hard links"));
        }
        if meta.uid() != nix::unistd::geteuid().as_raw() {
            return Err(refuse("it is owned by another user"));
        }
        if meta.mode() & 0o077 != 0 {
            return Err(refuse("it is accessible to other users"));
        }
    }
    std::fs::read_to_string(path)
        .map(Some)
        .map_err(|e| EngineError::io(path, e))
}

/// Write `bytes` to a fresh owner-only sibling, sync it, and rename it over
/// `path`.
fn write_private_atomic(path: &Path, bytes: &[u8]) -> Result<(), EngineError> {
    let dir = path.parent().unwrap_or(Path::new("."));
    let tmp = dir.join(format!(
        ".{}.{}.tmp",
        path.file_name().and_then(|n| n.to_str()).unwrap_or("tls"),
        uuid::Uuid::new_v4().simple()
    ));
    let result = (|| {
        let mut file = create_private_file_new(&tmp)?;
        file.write_all(bytes)
            .and_then(|_| file.sync_all())
            .map_err(|e| EngineError::io(&tmp, e))?;
        std::fs::rename(&tmp, path).map_err(|e| EngineError::io(path, e))
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&tmp);
    }
    result?;
    sync_private_dir(dir);
    Ok(())
}
