use crate::manifest::Manifest;
use anyhow::Result;
pub fn render(m: &Manifest) -> Result<String> {
    let mut s=format!("# Generated by cargo xtask gates render; edit ci/gates.toml.\nnextest-version = {:?}\n\n[profile.default]\nretries = 0\nfail-fast = false\nslow-timeout = {{ period = \"1s\", terminate-after = 20 }}\n\n[profile.default.junit]\npath = \"junit.xml\"\n\n",m.tools["nextest"].version);
    for (id, g) in &m.groups {
        // A per-runner group is an upper bound only; CI owns the host-wide lease.
        let max = g.max_threads.unwrap_or_else(|| {
            m.platforms
                .values()
                .filter_map(|p| p.max_vms)
                .min()
                .unwrap_or(1)
        });
        s.push_str(&format!("[test-groups.{id}]\nmax-threads = {max}\n\n"));
    }
    for (id, suite) in &m.suites {
        if suite.kind != "nextest" {
            continue;
        }
        let Some(target) = suite.target.as_deref() else {
            continue;
        };
        let target_filter = if target == "lib" {
            "kind(lib)".to_string()
        } else if let Some(t) = target.strip_prefix("test:") {
            format!("binary(={t})")
        } else {
            format!("binary(={})", target.strip_prefix("bin:").unwrap_or(target))
        };
        let mut filter = format!(
            "package(={}) & {target_filter}",
            suite.package.as_deref().unwrap_or_default()
        );
        if let Some(f) = &suite.filter {
            filter.push_str(&format!(" & ({f})"));
        }
        let seconds = suite
            .budget_seconds
            .or(m.tiers[&suite.tier].budget_seconds)
            .unwrap_or(600);
        s.push_str(&format!("# {id}\n[[profile.default.overrides]]\nfilter = {filter:?}\nslow-timeout = {{ period = \"1s\", terminate-after = {seconds} }}\n"));
        if let Some(group) = &suite.group {
            s.push_str(&format!("test-group = {group:?}\n"));
        }
        if suite.serial {
            s.push_str("threads-required = \"num-test-threads\"\n");
        }
        s.push('\n');
    }
    Ok(s)
}
