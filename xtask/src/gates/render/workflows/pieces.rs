/// `runs-on` value: a scalar for one label, a flow sequence for several.
pub fn runs_on(labels: &[String]) -> String {
    if labels.len() == 1 {
        labels[0].clone()
    } else {
        format!("[{}]", labels.join(", "))
    }
}

/// Re-indent a block (the first line is not indented: callers put it after a key).
pub fn indent(text: &str, spaces: usize) -> String {
    let pad = " ".repeat(spaces);
    text.lines()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{pad}{l}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Check out the commit under test. Credentials are never persisted: no job in
/// these workflows pushes with the checkout token.
pub fn checkout(depth0: bool) -> String {
    checkout_ref(depth0, "${{ inputs.ref || github.sha }}")
}

/// Same, with an explicit `ref` expression (workflows without a `ref` input).
pub fn checkout_ref(depth0: bool, reference: &str) -> String {
    let mut s = format!(
        "- name: Check out the commit under test\n  uses: {CHECKOUT}\n  with:\n    ref: {reference}\n    persist-credentials: false\n"
    );
    if depth0 {
        s.push_str("    fetch-depth: 0\n");
    }
    s
}

/// Install the pinned toolchain. `extra` lines are `components:`/`targets:` entries.
pub fn rust(toolchain: &str, extra: &[(&str, &str)]) -> String {
    let mut s = format!(
        "- name: Install Rust toolchain\n  uses: {RUST}\n  with:\n    toolchain: \"{toolchain}\"\n"
    );
    for (k, v) in extra {
        s.push_str(&format!("    {k}: {v}\n"));
    }
    s
}

/// Header shared by both workflows. `gates check` compares the whole file, so a
/// hand edit anywhere is drift.
pub fn header(name: &str) -> String {
    format!(
        "# GENERATED by `cargo xtask gates render` from ci/gates.toml. DO NOT EDIT BY HAND:\n# `cargo xtask gates check` rejects any difference from the rendered text.\n# Change the manifest or xtask/src/gates/render/workflows/, then re-render.\nname: {name}\n"
    )
}
