#!/usr/bin/env bash
# Uses pristine published migration crates from SOURCE_ROOT (as protocol compat).
# No VM, guest agent, host agent, credentials or hardware required; the final
# awman upgrade step needs this host's builtin payload (`make payloads`).
# AWMAN_UPDATE_CATALOG_FIXTURE=1 also refreshes the committed 0.7.2 fixture.
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
scratch=$(mktemp -d /tmp/awman-catalog-compat.XXXXXX)
trap 'rm -r -- "$scratch"' EXIT
if [ $# -gt 0 ]; then
    source_root=$(cd "$1" && pwd)
else
    source_root="$scratch/sources"
    mkdir "$source_root"
    for version in 0.7.2 0.7.8; do
        case "$version" in
            0.7.2) expected=9ded9890da64f3157aefc2352190328252c7ea1b667954570779ed4b14738c61;;
            0.7.8) expected=9658914aca55bb0d87283aa02e7487a5c11f5d67db035c5d29f80163e5c7b51d;;
        esac
        archive="$source_root/migration-$version.crate"
        curl -fsSL --retry 3 "https://static.crates.io/crates/microsandbox-migration/microsandbox-migration-$version.crate" -o "$archive"
        printf '%s  %s\n' "$expected" "$archive" | shasum -a 256 -c -
        tar xf "$archive" -C "$source_root"
    done
fi
export AWMAN_CATALOG_FIXTURE="$scratch/catalog.db"
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$repo/target}
for version in 0.7.2 0.7.8; do
    mkdir "$scratch/$version"
    cp "$repo/tools/test-fixtures/msb-catalog-compat.rs" "$scratch/$version/main.rs"
    cp "$repo/Cargo.lock" "$scratch/$version/Cargo.lock"
    cat > "$scratch/$version/Cargo.toml" <<EOF
[package]
name = "awman-catalog-compat"
version = "0.0.0"
edition = "2021"
[workspace]
[[bin]]
name = "awman-catalog-compat"
path = "main.rs"
[dependencies]
microsandbox-migration = { path = "$source_root/microsandbox-migration-$version" }
sea-orm = { version = "2.0.0", default-features = false, features = ["sqlx-sqlite", "runtime-tokio-rustls"] }
serde_json = "1"
tokio = { version = "1", features = ["macros", "rt-multi-thread"] }
[patch.crates-io]
sqlx-sqlite = { path = "$repo/third_party/sqlx-sqlite-0.9.0" }
EOF
    if [ "$version" = 0.7.8 ]; then
        printf 'microsandbox-types = { path = "%s/third_party/microsandbox-types-0.7.8" }\n' "$repo" >> "$scratch/$version/Cargo.toml"
    fi
done
for step in '0.7.2 write-old' '0.7.8 upgrade-new' '0.7.2 refuse-old' '0.7.8 verify-new'; do
    read -r version phase <<< "$step"
    cargo run --quiet --manifest-path "$scratch/$version/Cargo.toml" -- "$phase"
    if [ "$phase" = write-old ]; then
        cp "$AWMAN_CATALOG_FIXTURE" "$scratch/msb-catalog-0.7.2.db"
        # The committed fixture (tests/builtin_runtime/fixtures) is consumed by
        # the upgrade tests and stays generated by the published 0.7.2
        # migrator. Refresh it only on request, so a run leaves the tree clean.
        if [ "${AWMAN_UPDATE_CATALOG_FIXTURE:-}" = 1 ]; then
            fixture_dir="$repo/tests/builtin_runtime/fixtures"
            mkdir -p "$fixture_dir"
            cp "$AWMAN_CATALOG_FIXTURE" "$fixture_dir/msb-catalog-0.7.2.db"
        fi
    fi
done
# The same 0.7.2 catalog through awman's own upgrade (prepare_catalog and
# upgrade_catalog with the pinned SDK), not only the raw migrations above.
host=$(rustc -vV | sed -n 's/^host: //p')
if bash "$repo/tools/msb-payloads/verify.sh" "$host" > /dev/null 2>&1; then
    (cd "$repo" && AWMAN_TEST_CATALOG_072="$scratch/msb-catalog-0.7.2.db" cargo test --quiet --locked \
        --features builtin-runtime --lib -- --exact \
        engine::container::builtin::msb_driver::tests::sdk_upgrade_of_a_072_catalog_retires_only_stale_awman_sandboxes_and_keeps_images)
else
    echo "BLOCKED: prepare_catalog upgrade: no verified builtin payload for $host (run \`make payloads\`)" >&2
    exit 2
fi
